import { build } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const root = new URL('../', import.meta.url);
const metadata = await readFile(new URL('src/userscript.meta.txt', root), 'utf8');
const { version } = JSON.parse(await readFile(new URL('package.json', root), 'utf8'));

if (!metadata.startsWith('// ==UserScript==\n') || !metadata.trimEnd().endsWith('// ==/UserScript==')) {
  throw new Error('Invalid userscript metadata block');
}
if (!metadata.includes(`// @version        ${version}\n`)) {
  throw new Error('package.json and userscript metadata versions must agree');
}

const result = await build({
  absWorkingDir: fileURLToPath(root),
  entryPoints: ['src/index.js'],
  bundle: true,
  format: 'iife',
  platform: 'browser',
  target: ['es2020'],
  charset: 'utf8',
  legalComments: 'none',
  write: false,
});
const output = `${metadata}\n// Generated by npm run build. Edit src/ instead.\n${result.outputFiles[0].text}`;
const destination = new URL('userscript.js', root);

if (process.argv.includes('--check')) {
  if (await readFile(destination, 'utf8') !== output) {
    throw new Error('userscript.js is out of date. Run npm run build and commit it.');
  }
  console.log('userscript.js is up to date.');
} else {
  await writeFile(destination, output);
  console.log('Built userscript.js');
}
